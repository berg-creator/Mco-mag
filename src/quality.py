"""Отбраковка постов перед попаданием в очередь.

Модель нестабильна: то вернёт служебный JSON вместо текста, то сползёт
в язык пресс-релиза, то подставит правдоподобный год, которого не было
во входных данных. Такое дешевле поймать автоматически и перегенерировать,
чем показывать читателям: в моде выдумка ловится мгновенно и стоит канала.

Проверки намеренно грубые — цель отсечь явный брак, а не оценивать стиль.
Единственная тонкая проверка здесь — сверка годов и цифр с фактами из базы:
это главный риск продукта, и он стоит того, чтобы считать его отдельно.
"""

from __future__ import annotations

import json
import re

# Обороты, прямо запрещённые голосом канала. Их наличие означает, что модель
# ушла в пересказ пресс-релиза — ровно то, чем занята сотня каналов про дропы.
BANNED_PHRASES = (
    "лаконичный силуэт",
    "must-have",
    "маст-хэв",
    "маст хэв",
    "стильный образ",
    "модный образ",
    "в этом сезоне актуально",
    "актуален в этом сезоне",
    "идеально дополнит",
    "гардероб настоящего мужчины",
    "не выходит из моды",
    "вне времени",
    "икона стиля",
    "символ эпохи",
    "давайте разберёмся",
    "давайте разберемся",
    "стоит отметить",
    "как известно",
    "подводя итог",
    "таким образом",
    "уважаемые подписчики",
    "всем привет",
    "друзья,",
)

# Слова-пустышки: одно простительно, два и больше — это вода вместо фактов.
# Ими обычно подменяют разговор о вещи: выглядит как описание, не сообщает
# ничего проверяемого.
FILLER_WORDS = (
    "культовый",
    "культовая",
    "легендарный",
    "легендарная",
    "знаковый",
    "знаковая",
    "поистине",
    "по-настоящему",
    "уникальный дизайн",
    "неповторимый",
    "изысканн",
    "утончённ",
    "премиальн",
    "вайб",
    "эстетика бренда",
)

# Пост почти всегда уходит подписью к фотографии, а её потолок — 1024 знака.
# Поэтому верхняя граница ниже, чем у обычного сообщения: пост, который
# не влезает в подпись, придётся отправлять текстом и без картинки.
#
# Запас в сотню знаков — под строку атрибуции: фото с Wikimedia уходит
# с именем автора и лицензией (до 90 знаков), и без этой строки его брать
# нельзя вовсе. Пост на 950 знаков остался бы без картинки именно из-за неё.
MIN_LENGTH = 200
MAX_LENGTH = 900

_TAGS = re.compile(r"<[^>]+>")
_YEAR = re.compile(r"\b(1[89]\d{2}|20\d{2})\b")


def plain(text: str) -> str:
    """Текст без HTML-разметки — Telegram считает длину подписи так же."""
    return _TAGS.sub("", text)


def unverified_years(text: str, payload: dict) -> list[str]:
    """Годы из поста, которых нет во входных данных.

    Самая частая и самая дорогая выдумка — правдоподобная дата: «основан
    в 1974-м» вместо 1971-го читатель ловит сразу, а доверие возвращается
    годами. Проверка тупая (подстрока в сериализованных данных) и потому
    надёжная: год либо есть в фактах, либо модель его придумала.
    """
    facts = json.dumps(payload, ensure_ascii=False)
    return sorted({year for year in _YEAR.findall(plain(text)) if year not in facts})


def problems(text: str, rubric: str, payload: dict | None = None) -> list[str]:
    """Список причин, по которым пост нельзя публиковать. Пусто — годится."""
    issues: list[str] = []
    stripped = text.strip()

    if not stripped:
        return ["пустой текст"]

    visible = plain(stripped)

    if len(visible) < MIN_LENGTH:
        issues.append(f"слишком короткий ({len(visible)} знаков)")
    if len(visible) > MAX_LENGTH:
        issues.append(f"не влезет в подпись к фото ({len(visible)} знаков)")

    # Служебный JSON, просочившийся в текст поста.
    if stripped.startswith("{") or '"skip"' in stripped or '"text":' in stripped:
        issues.append("в текст попал служебный JSON")

    # Литеральные «\n» вместо настоящих переводов строки.
    if "\\n" in stripped:
        issues.append("экранированные переводы строк вместо настоящих")

    lowered = visible.lower()
    for phrase in BANNED_PHRASES:
        if phrase in lowered:
            issues.append(f"запрещённый оборот: «{phrase}»")

    filler_hits = [w for w in FILLER_WORDS if w in lowered]
    if len(filler_hits) >= 2:
        issues.append(f"слова-пустышки: {', '.join(filler_hits)}")

    # Разметка, которую Telegram не разберёт: пост с ней не отправится вовсе.
    if re.search(r"<\s*(br|p|ul|ol|li|h[1-6]|div)\b", stripped, re.IGNORECASE):
        issues.append("неподдерживаемые HTML-теги")

    # Вопрос в конце — не украшение: комментарии под постом дают
    # алгоритмический вес и повод вернуться. Ищем в последней трети текста,
    # потому что вопрос в середине этой работы не делает.
    tail = visible[-300:]
    if "?" not in tail:
        issues.append("нет вопроса читателю в конце")

    # Фирменный формат: ключевая мысль цитатой, досье строкой моноширинного.
    # Без проверки модель сползает на обычный жирный текст, и канал перестаёт
    # отличаться в ленте от соседних — а это единственное, чем он и берёт.
    if stripped.count("<blockquote>") != 1:
        issues.append("ключевая мысль должна быть ровно одной цитатой <blockquote>")
    if stripped.count("<code>") != 1:
        issues.append("нет досье строкой <code> — или их больше одной")

    if payload is not None:
        strays = unverified_years(stripped, payload)
        if strays:
            issues.append(f"годы, которых нет в фактах: {', '.join(strays)}")

    return issues


def is_ok(text: str, rubric: str, payload: dict | None = None) -> bool:
    return not problems(text, rubric, payload)
